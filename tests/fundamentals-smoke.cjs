// Requires Playwright and Chrome, like the other browser smoke checks.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const root = path.resolve(__dirname, '..');
const url = process.env.PREVIEW_URL || 'http://127.0.0.1:4173';
const snapshot = JSON.parse(fs.readFileSync(path.join(root,'data/fundamentals.json'),'utf8'));
const bbca = snapshot.stocks.find(stock => stock.series_id === 'BBCA');
const excl = snapshot.stocks.find(stock => stock.series_id === 'EXCL');
const number = (value, locale='en-US') => new Intl.NumberFormat(locale,{maximumFractionDigits:2}).format(value);
(async () => {
  const browser = await chromium.launch({channel:'chrome', headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.waitForSelector('.fundamental-card dd');
    assert.equal(await page.locator('.fundamental-card').count(), 1, 'default shows only selected BBCA stock, not index, gold or FX');
    assert.equal(await page.locator('.fundamental-card dd').count(), 5);
    assert.match(await page.locator('.fundamental-industry').innerText(), /Banks/);
    assert.equal(await page.locator('[data-stock="BBCA"] dd').nth(4).innerText(), number(bbca.roa_pct) + '%');
    const bbcaDetails = page.locator('[data-stock="BBCA"] .fundamental-details');
    assert.equal(await bbcaDetails.evaluate(el => el.open), false, 'secondary details start closed');
    await bbcaDetails.locator('summary').focus();
    await page.keyboard.press('Enter');
    assert.equal(await bbcaDetails.evaluate(el => el.open), true, 'details work with the keyboard');
    assert.equal(await bbcaDetails.locator('.fundamental-leverage').count(), 0, 'bank leverage is not presented as comparable company debt');
    const displayedIndexes = await bbcaDetails.locator('.index-memberships span').allTextContents();
    assert.ok(displayedIndexes.every(code => ['LQ45','IDX30','IDX80','KOMPAS100','ISSI','JII','JII70'].includes(code)));
    await page.click('[data-language="id"]');
    assert.equal(await bbcaDetails.evaluate(el => el.open), true, 'changing language preserves expanded details');
    assert.match(await page.locator('.fundamental-industry').innerText(), /Perbankan/);
    await page.click('[data-language="en"]');
    await bbcaDetails.locator('summary').click();
    assert.match(await page.locator('#fundamentalsDate').innerText(), /Collected/);
    assert.equal(await page.locator('[data-stock="BBCA"] dd').nth(1).innerText(), bbca.pe_ttm > 0 ? number(bbca.pe_ttm) + '×' : 'Not meaningful');
    const before = await page.locator('#fundamentalsCards').innerText();
    await page.selectOption('#currencySelect', 'USDIDR');
    await page.click('[data-range="1Y"]');
    assert.equal(await page.locator('#fundamentalsCards').innerText(), before, 'snapshot stays in IDR and does not masquerade as historical fundamentals');
    await page.click('[data-preset="banks"]');
    assert.equal(await page.locator('.fundamental-card').count(), 4);
    await page.locator('#companyFundamentals').screenshot({path:'/tmp/id-market-fundamentals-desktop.png'});
    const selection = await page.evaluate(() => JSON.stringify([...state.selectedSeries]));
    await page.click('#stockToggleSummary');
    await page.click('#idxFilters > summary');
    assert.equal(await page.locator('#stockToggleDropdown').evaluate(el => el.open), true, 'opening nested filters leaves the picker open');
    await page.selectOption('#assetIndustry','Banks');
    await page.selectOption('#assetIndex','LQ45');
    const expectedBanks = snapshot.stocks.filter(s => s.industry === 'Banks' && s.index_memberships.includes('LQ45')).map(s => s.series_id).sort();
    assert.deepEqual((await page.locator('#stockToggleList input').evaluateAll(inputs => inputs.map(el => el.value))).sort(), expectedBanks);
    assert.equal(await page.evaluate(() => JSON.stringify([...state.selectedSeries])), selection, 'filtering never changes the comparison');
    assert.match(await page.locator('#idxFilterCount').innerText(), /2 active/);
    await page.selectOption('#assetCountry','Australia');
    assert.equal(await page.locator('#idxFilters').isVisible(), false);
    assert.equal(await page.locator('#stockToggleList input').count(), 3, 'hidden Indonesian filters do not restrict other markets');
    await page.selectOption('#assetCountry','all');
    await page.fill('#stockToggleSearch','zzzz-no-match');
    assert.ok(await page.locator('#clearStockFilters').isVisible(), 'empty results retain a clear recovery action');
    await page.fill('#stockToggleSearch','');
    await page.locator('.stock-toggle-panel').screenshot({path:'/tmp/id-market-stock-filters-desktop.png'});
    await page.click('#clearStockFilters');
    assert.equal(await page.locator('#idxFilterCount').innerText(), '');
    await page.click('#idxFilters > summary');
    await page.fill('#stockToggleSearch','EXCL');
    await page.check('#stockToggleList input[value="EXCL"]');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-stock="EXCL"] dd').nth(1).innerText(), excl.pe_ttm > 0 ? number(excl.pe_ttm) + '×' : 'Not meaningful');
    assert.equal(await page.locator('[data-stock="EXCL"] dd').nth(3).innerText(), number(excl.roe_pct) + '%');
    await page.locator('[data-stock="EXCL"] .fundamental-details > summary').click();
    assert.match(await page.locator('[data-stock="EXCL"] .fundamental-leverage').innerText(), /Liabilities \/ equity/);
    assert.equal(await page.locator('[data-stock="EXCL"] .fundamental-detail-value').innerText(), number(excl.liabilities_equity) + '×');
    await page.click('[data-language="id"]');
    assert.match(await page.locator('#companyFundamentals > summary').innerText(), /Fundamental perusahaan/);
    assert.equal(await page.locator('[data-stock="BBCA"] dd').nth(1).innerText(), bbca.pe_ttm > 0 ? number(bbca.pe_ttm,'id-ID') + '×' : 'Tidak bermakna');
    assert.equal(await page.locator('[data-stock="EXCL"] dd').nth(1).innerText(), excl.pe_ttm > 0 ? number(excl.pe_ttm,'id-ID') + '×' : 'Tidak bermakna');
    await page.click('.fundamentals-help > summary');
    assert.match(await page.locator('.fundamentals-help').innerText(), /Harga saham/);
    await page.click('[data-language="en"]');
    await page.click('[data-preset="banks"]');
    await page.setViewportSize({width:375,height:900});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no mobile horizontal overflow');
    assert.ok(await page.locator('[data-stock="BBCA"] dd').first().isVisible());
    await page.locator('#companyFundamentals').screenshot({path:'/tmp/id-market-fundamentals-mobile.png'});
    await page.click('#stockToggleSummary');
    await page.fill('#stockToggleSearch','');
    await page.click('#idxFilters > summary');
    await page.selectOption('#assetIndustry','Banks');
    await page.selectOption('#assetIndex','ISSI');
    assert.ok((await page.locator('#assetIndustry').boundingBox()).height >= 44);
    assert.ok((await page.locator('#assetIndex').boundingBox()).height >= 44);
    assert.ok(await page.locator('#stockToggleList input').count() > 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.ok((await page.locator('.stock-toggle-panel').boundingBox()).height <= 720, 'expanded picker is bounded on mobile');
    await page.locator('.stock-toggle-panel').screenshot({path:'/tmp/id-market-stock-filters-mobile.png'});
    await page.click('#clearStockFilters');
    await page.keyboard.press('Escape');
    await page.click('#resetSelections');
    assert.equal(await page.evaluate(() => state.assetIndustry + ':' + state.assetIndex), 'all:all');
    await page.setViewportSize({width:1440,height:1100});
    await page.click('[data-collection="world"]');
    await page.click('[data-preset="us"]');
    assert.match(await page.locator('#fundamentalsCards').innerText(), /Fundamentals currently cover Indonesian stocks/);
    await page.click('[data-collection="indonesia"]');
    await page.click('[data-preset="market"]');
    assert.equal(await page.locator('.fundamental-card').count(), 1, 'ASII is the only stock in the market preset');
    await page.evaluate(() => {state.selectedSeries = new Set(['IHSG','GOLD']); render();});
    assert.match(await page.locator('#fundamentalsCards').innerText(), /Add a stock/);
    await page.route('**/data/fundamentals.json', route => route.fulfill({contentType:'application/json', body:'{"schema_version":1,"stocks":[null]}'}));
    await page.reload();
    await page.waitForSelector('[data-stock="BBCA"] dd');
    assert.equal(await page.locator('[data-stock="BBCA"] dd').count(), 5, 'malformed HTTP snapshot falls back to embedded data');
    await page.unroute('**/data/fundamentals.json');
    // Neither optional data source available: the existing price app still loads.
    const html = fs.readFileSync(path.join(root,'index.html'),'utf8').replace(/(<script id="embedded-fundamentals-json" type="application\/json">)[\s\S]*?(<\/script>)/, '$1null$2');
    await page.route(url + '/', route => route.fulfill({contentType:'text/html',body:html}));
    await page.route('**/data/fundamentals.json', route => route.fulfill({status:503,body:'unavailable'}));
    await page.goto(url + '/');
    await page.waitForSelector('#chart polyline');
    assert.match(await page.locator('#fundamentalsCards').innerText(), /Snapshot unavailable/);
    await page.unrouteAll({behavior:'wait'});
    await page.goto(pathToFileURL(path.join(root,'index.html')).href);
    await page.waitForSelector('[data-stock="BBCA"] dd');
    assert.equal(await page.locator('[data-stock="BBCA"] dd').count(), 5, 'direct file opening uses embedded snapshot');
    assert.deepEqual(errors, []);
    console.log('Fundamentals browser checks passed: desktop, mobile, language, selection, date/currency independence, fallback and offline.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
