let language = 'en';
function preferredLanguage() {
  if (typeof window !== 'undefined') {
    const params = new URLSearchParams(window.location.hash.slice(1));
    if (params.get('v') === '1' && ['en', 'id'].includes(params.get('lang'))) return params.get('lang');
  }
  try {
    const saved = localStorage.getItem('id-market-language');
    if (saved === 'en' || saved === 'id') return saved;
  } catch { /* Storage can be unavailable when opening a local file. */ }
  return typeof navigator !== 'undefined' && /^id(?:-|$)/i.test(navigator.language) ? 'id' : 'en';
}
function locale() { return language === 'id' ? 'id-ID' : 'en-US'; }
function t(key, ...values) {
  return (language === 'id' ? INDONESIAN[key] || key : key).replace(/\{(\d+)\}/g, (_, index) => values[index] ?? '');
}
function decimal(value, digits) {
  return value.toLocaleString(locale(), {minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false});
}
// Capture only static page copy, once. Updating text nodes preserves links and controls.
const staticTranslations = [];
function setupLanguage() {
  language = preferredLanguage();
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style, .brand')) continue;
    const key = node.textContent.trim();
    if (INDONESIAN[key]) staticTranslations.push(() => {
      if (node.isConnected) node.textContent = node.textContent.replace(node.textContent.trim(), t(key));
    });
  }
  document.querySelectorAll('[aria-label], [placeholder], [title]').forEach(element => {
    for (const attribute of ['aria-label', 'placeholder', 'title']) {
      const key = element.getAttribute(attribute);
      if (INDONESIAN[key]) staticTranslations.push(() => element.setAttribute(attribute, t(key)));
    }
  });
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
      language = button.dataset.language;
      try { localStorage.setItem('id-market-language', language); } catch { /* Choice still works for this visit. */ }
      applyLanguage();
      if (!state.allDates.length) return;
      populateDateSelects();
      renderCollections();
      render();
    });
  });
  applyLanguage();
}
function applyLanguage() {
  document.documentElement.lang = language;
  document.title = language === 'id' ? 'ID Market — sudut pandang lebih luas' : 'ID Market — a wider perspective';
  staticTranslations.forEach(update => update());
  document.querySelectorAll('[data-language]').forEach(button => {
    const active = button.dataset.language === language;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', active);
  });
  document.querySelectorAll('#assetCountry option').forEach(option => {
    option.textContent = t(option.value === 'all' ? 'All markets' : option.value);
  });
  if (state.allDates.length) updateCoverage();
}
